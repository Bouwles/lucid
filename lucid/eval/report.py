"""Plots and the Markdown results section written by scripts/evaluate.py."""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402


def plot_curves(
    curves: dict[str, dict[int, float]], ylabel: str, path: str | Path, logx: bool = True
) -> None:
    """curves: {label: {step: value}}."""
    fig, ax = plt.subplots(figsize=(6, 4), dpi=120)
    for label, c in curves.items():
        xs = sorted(c)
        ax.plot(xs, [c[x] for x in xs], marker="o", label=label)
    if logx:
        ax.set_xscale("log", base=2)
    ax.set_xlabel("rollout step")
    ax.set_ylabel(ylabel)
    ax.grid(alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def plot_band(
    values: dict[str, list[float]], lo: float, hi: float, ylabel: str, path: str | Path
) -> None:
    """Feature over a long rollout, with the real-data range shaded."""
    fig, ax = plt.subplots(figsize=(7, 3.5), dpi=120)
    ax.axhspan(lo, hi, color="grey", alpha=0.2, label="real range")
    for label, v in values.items():
        ax.plot(v, lw=0.8, label=label)
    ax.set_xlabel("rollout step")
    ax.set_ylabel(ylabel)
    ax.legend(loc="upper right", fontsize=7)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def fmt(v, nd: int = 4) -> str:
    if v is None:
        return "not measured"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def results_section(res: dict) -> str:
    """Build the Markdown section from evaluate.py's results dict."""
    L = [
        f"## Evaluation: {res['run']} (step {res['step']})",
        "",
        f"Checkpoint `{res['checkpoint']}`, dataset `{res['dataset_version']}`, git `{res['git_commit']}`, "
        f"sampler {res['sampler']}. Generated by scripts/evaluate.py; **pending eval-auditor check**.",
        "",
        "### One-step (teacher-forced)",
        "",
        "| Split | N | PSNR | SSIM | LPIPS |",
        "|---|---|---|---|---|",
    ]
    for split, m in res["one_step"].items():
        L.append(
            f"| {split} | {m['n']} | {fmt(m.get('psnr'), 2)} | {fmt(m.get('ssim'))} | {fmt(m.get('lpips'))} |"
        )
    L += ["", "### Free-running LPIPS by step", "", "![lpips curve](lpips_curve.png)", ""]
    for label, c in res["rollout_curves"].items():
        L.append(
            f"- {label}: "
            + ", ".join(f"@{s} {fmt(v)}" for s, v in sorted(c.items(), key=lambda x: int(x[0])))
        )
    st = res.get("stability")
    if st:
        L += [
            "",
            "### Long-horizon stability",
            "",
            f"{st['n']} free-running rollouts of {st['steps']} steps with scripted random actions. "
            f"Median survival time {st['median_survival']} steps (min {st['min_survival']}, max {st['max_survival']}).",
            "",
            "![sharpness](sharpness.png)",
        ]
    ctrl = res.get("controllability")
    if ctrl:
        L += [
            "",
            "### Controllability",
            "",
            "| Action | Dream | Real game | N (dream) |",
            "|---|---|---|---|",
        ]
        real = res.get("controllability_real", {})
        for name, c in ctrl.items():
            r = real.get(name, {}).get("score")
            L.append(
                f"| {name} | {c['score']:.1%} | {'not measured' if r is None else f'{r:.1%}'} | {c['n']} |"
            )
        L += [
            "",
            "Null-action bracket: not measured yet (train a copy with model.p_uncond_action=1.0).",
        ]
    if res.get("probe_accuracy"):
        L += [
            "",
            "Probe accuracy on real held-out frames: "
            + ", ".join(f"{k} {v:.1%}" for k, v in res["probe_accuracy"].items()),
        ]
    if res.get("realism"):
        r = res["realism"]
        L += [
            "",
            "### Real-vs-dream classifier",
            "",
            f"Accuracy at step 1: {r[0]:.1%}, at the last step: {r[-1]:.1%} (50% means it cannot tell).",
        ]
    if res.get("speed"):
        s = res["speed"]
        L += [
            "",
            f"Generation speed on {s['device']}: {s['ms_per_frame']:.1f} ms per frame ({s['fps']:.1f} FPS), batch 1.",
        ]
    L += [
        "",
        "### Failure gallery",
        "",
        "The shortest-surviving rollouts are in `failures/`. Pick the clear ones by eye.",
        "",
    ]
    return "\n".join(L) + "\n"
